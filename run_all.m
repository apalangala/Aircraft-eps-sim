function R = run_all(varargin)
%RUN_ALL  Regenerate every result in the project.
%
%   RUN_ALL() runs, in order:
%     1. the single-line diagram,
%     2. all fault scenarios (scenarios/scenario_list.m) with plots,
%     3. the design studies (battery sizing, radar headroom, transients,
%        pulsed radar, stability, reliability),
%     4. the test suite,
%   and writes figures to results/figures, tables to results/, and a
%   generated summary of every headline number to results/summary.md.
%
%   RUN_ALL('noscenarios') skips step 2 (the slowest part).
%   RUN_ALL('notests') skips step 4.
%
%   Runs in MATLAB R2019b or newer and in GNU Octave 8 or newer.
%   Typical run time: a few minutes in MATLAB, ~15 minutes in Octave.

root = setup_paths();
do_scen = ~any(strcmpi(varargin, 'noscenarios'));
do_tests = ~any(strcmpi(varargin, 'notests'));
figdir = fullfile(root, 'results', 'figures');
resdir = fullfile(root, 'results');
if ~exist(figdir, 'dir'), mkdir(figdir); end
t_all = tic;

p = eps_params();
L = load_table();
m = mission_profile();

fprintf('\n== Aircraft electrical power system simulator ==\n');
plot_single_line_diagram(p, fullfile(figdir, 'single_line_diagram.png'));

% ---- scenarios -----------------------------------------------------------
R.scen = struct('name', {}, 'title', {}, 'summary', {});
if do_scen
    S = scenario_list();
    fprintf('\nScenarios\n');
    for k = 1:numel(S)
        t0 = tic;
        out = run_system_sim(S(k), p, L, m);
        plot_scenario(out, fullfile(figdir, ['scenario_' S(k).name '.png']));
        R.scen(k).name = S(k).name;
        R.scen(k).title = S(k).title;
        R.scen(k).summary = out.summary;
        fprintf('  %-34s done in %5.1f s\n', S(k).name, toc(t0));
    end
    write_scenario_csv(fullfile(resdir, 'scenario_summary.csv'), R.scen, L);
end

% ---- studies -------------------------------------------------------------
fprintf('\nDesign studies\n');
t0 = tic; R.battery = study_battery_sizing(p, L, m, figdir);      fprintf('  battery sizing      %5.1f s\n', toc(t0));
t0 = tic; R.radar = study_radar_headroom(p, L, m, figdir);        fprintf('  radar headroom      %5.1f s\n', toc(t0));
tp = transient_params();
t0 = tic; R.transients = study_transients(tp, figdir);            fprintf('  transients          %5.1f s\n', toc(t0));
t0 = tic; R.pulsed = study_pulsed_radar(tp, figdir);              fprintf('  pulsed radar        %5.1f s\n', toc(t0));
t0 = tic; R.stability = study_stability(tp, figdir);              fprintf('  stability           %5.1f s\n', toc(t0));
t0 = tic; R.reliability = study_reliability(m, figdir);           fprintf('  reliability         %5.1f s\n', toc(t0));

write_summary(fullfile(resdir, 'summary.md'), R, p, L);

% ---- tests ---------------------------------------------------------------
if do_tests
    R.tests = run_all_tests();
end
fprintf('All done in %.1f min. Results in %s\n', toc(t_all) / 60, resdir);
end

% =========================================================================
function write_scenario_csv(fname, scen, L)
fid = fopen(fname, 'w');
fprintf(fid, 'scenario,p1_unpowered_s,generators_paralleled,max_sources_per_island,soc_min,soc_end,battery_depleted,battery_only_min,apu_online_s,hv_min_V,hv_max_V,lv_min_V,lv_max_V,steady_state_ok,energy_not_served_kWh,loads_shed\n');
for k = 1:numel(scen)
    s = scen(k).summary;
    hv = [s.Vmin.HV1 s.Vmin.HV2 s.Vmin.HVE];
    hx = [s.Vmax.HV1 s.Vmax.HV2 s.Vmax.HVE];
    shed = find(s.n_shed_events > 0);
    names = strjoin(arrayfun(@(i) strrep(L(i).name, ',', ''), shed, 'UniformOutput', false), '; ');
    fprintf(fid, '%s,%.2f,%d,%d,%.3f,%.3f,%d,%.1f,%.2f,%.1f,%.1f,%.2f,%.2f,%d,%.2f,%s\n', ...
        scen(k).name, s.p1_unpowered_s, s.gens_ever_paralleled, s.max_sources_per_island, ...
        s.soc_min, s.soc_end, s.batt_depleted, s.batt_emergency_s / 60, s.apu_online_t, ...
        min(hv(~isnan(hv))), max(hx(~isnan(hx))), s.Vmin.LV, s.Vmax.LV, s.hv_ss_ok && s.lv_ss_ok, ...
        sum(s.energy_not_served_kWh), names);
end
fclose(fid);
end

function write_summary(fname, R, p, L)
fid = fopen(fname, 'w');
w = @(varargin) fprintf(fid, varargin{:});
w('# Results summary\n\n');
w('Generated by `run_all.m`. Every number below comes from the code in this repository.\n\n');

if ~isempty(R.scen)
    w('## Fault scenarios\n\n');
    w('| Scenario | P1 loads unpowered | Loads shed (count) | Battery SOC min | 270 V range (V) | 28 V range (V) |\n');
    w('|---|---|---|---|---|---|\n');
    for k = 1:numel(R.scen)
        s = R.scen(k).summary;
        hv = [s.Vmin.HV1 s.Vmin.HV2 s.Vmin.HVE];
        hx = [s.Vmax.HV1 s.Vmax.HV2 s.Vmax.HVE];
        w('| %s | %.0f s | %d | %.0f %% | %.1f to %.1f | %.2f to %.2f |\n', R.scen(k).title, s.p1_unpowered_s, ...
            sum(s.n_shed_events > 0), 100 * s.soc_min, min(hv(~isnan(hv))), max(hx(~isnan(hx))), s.Vmin.LV, s.Vmax.LV);
    end
    w('\n');
end

b = R.battery;
w('## Battery sizing (dual generator failure, APU fails, 30 min to touchdown)\n\n');
w('| Case | Minimum parallel strings | What limits it |\n|---|---|---|\n');
for c = 1:numel(b.cases)
    w('| %s | %d | %s |\n', b.cases(c).name, b.Np_min(c), b.limiting_reason{c});
end
w('\n- Design: **74S%dP**, %.0f Ah, %.1f kWh nominal, about **%.0f kg** including packaging.\n', ...
    b.Np_design, b.pack_Ah, b.pack_energy_kWh, b.pack_mass_kg);
w('- The 30 min profile only needs **%.1f kWh** at the terminals. The pack is %.1f times bigger because a cold, aged pack cannot hold its voltage during the %.0f kW landing peak.\n', ...
    b.E_required_kWh, b.pack_energy_kWh / b.E_required_kWh, max(b.prof.P_batt) / 1e3);
w('- Keeping the pack at 25 degC (heater) would cut it to %dP, saving about %.0f kg.\n\n', ...
    b.Np_min(3), (b.Np_design - b.Np_min(3)) * p.batt.Ns * p.batt.m_cell * p.batt.pack_mass_factor);

r = R.radar;
w('## Radar power headroom (mission phase, ECS follows radar)\n\n');
w('| Configuration | Max radar average power | Limiting source | Loading at baseline %g kW |\n|---|---|---|---|\n', r.baseline_radar_kW);
for c = 1:numel(r.cfg_names)
    w('| %s | %.1f kW | %s | %.0f %% |\n', r.cfg_names{c}, r.threshold_kW(c), r.binding_at_threshold{c}, 100 * r.loading_at_baseline(c));
end
w('\n');

t = R.transients;
w('## Transients vs MIL-STD-704F (270 V DC)\n\n');
w('| Event | Peak / dip | Result |\n|---|---|---|\n');
w('| Load application 15 -> 60 kW | min %.1f V | %s |\n', t.application.v_min, pf(t.application.pass));
w('| Load rejection 60 -> 15 kW | max %.1f V | %s |\n', t.rejection.v_max, pf(t.rejection.pass));
w('| Bus transfer, no soft start | max %.1f V, interruption %.1f ms | %s |\n', t.transfer_hard.v_max, 1e3 * t.transfer_hard.interruption_s, pf(t.transfer_hard.pass));
w('| Bus transfer, %.0f ms soft start | max %.1f V, interruption %.1f ms | %s |\n\n', 1e3 * t.soft_start_ramp_s, t.transfer_soft.v_max, 1e3 * t.transfer_soft.interruption_s, pf(t.transfer_soft.pass));

q = R.pulsed;
w('## Pulsed radar (%.0f kW bursts, %.0f %% duty, %.0f Hz)\n\n', q.P_peak_W / 1e3, 100 * q.duty, q.prf_Hz);
w('- Without a buffer the bus ripple is **%.1f V** (limit %.0f V).\n', q.ripple_no_buffer_V, q.ripple_limit_V);
w('- A buffer with time constant **%.1f ms** meets the limit. It swings **%.0f J**, about **%.1f mF** of capacitance used between %d and %d V.\n\n', ...
    1e3 * q.tau_required_s, q.E_required_J, 1e3 * q.C_required_F, q.V_window(1), q.V_window(2));

s = R.stability;
w('## Constant-power-load stability (radar PSU input filter)\n\n');
w('- LC filter only: unstable above **%.1f kW** (ideal-source estimate %.1f kW). The radar runs at 25 kW, so it would oscillate.\n', s.P_crit_undamped_W / 1e3, s.P_crit_simple_W / 1e3);
w('- With an R-C damping branch: stable across the 0-80 kW sweep. Minor-loop phase margin at 25 kW: **%.0f deg**, vector margin %.2f.\n', s.minor_loop_pm_deg, s.minor_loop_vector_margin);
w('- The impedances still overlap near the %.0f Hz generator/bus resonance, so Middlebrook''s conservative condition is not met.\n\n', s.bus_resonance_Hz);

e = R.reliability;
w('## Loss of the essential bus (per flight hour)\n\n');
w('- Baseline: **%.1e** (target 1e-9). Dominated by the single essential busbar (%.1e).\n', e.baseline_per_fh, e.contrib.hve_fault);
w('- Split essential bus with %.1f %% common cause: **%.1e**. Meets the target if common cause stays below %.1f %%.\n', 100 * e.beta_bus, e.split_per_fh, 100 * e.split_beta_max);
w('- Monte Carlo check (rates x%d): fault tree %.3g, Monte Carlo %.3g +/- %.2g.\n', e.scale, e.check_ft, e.check_mc, e.check_ci95);
fclose(fid);
end

function s = pf(ok)
if ok, s = 'PASS'; else, s = 'FAIL'; end
end
